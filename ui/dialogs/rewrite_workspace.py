"""AI 优化的任务设置与讲稿对照布局。"""

from PySide6.QtCore import Qt
from PySide6.QtGui import QColor
from PySide6.QtWidgets import QFrame, QHBoxLayout, QSplitter, QStackedWidget, QVBoxLayout, QWidget
from qfluentwidgets import (
    BodyLabel, CaptionLabel, CheckBox, ComboBox, HorizontalSeparator, ListWidget,
    PrimaryPushButton, ProgressBar, PushButton, ScrollArea,
    StrongBodyLabel, SubtitleLabel, setCustomStyleSheet,
)
from ui.dialogs.rewrite_widgets import (
    ManuscriptPageDelegate, WorkspaceSwitch, metadata_label as _muted,
    text_editor as _editor, workspace_frame as _frame,
)


def _pane(label, editor, parent):
    pane = QWidget(parent)
    layout = QVBoxLayout(pane)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(12)
    label.setFixedHeight(24)
    layout.addWidget(label)
    layout.addWidget(editor, 1)
    return pane


class RewriteWorkspace:
    def setup_workspace(self):
        self.setWindowTitle('AI 优化')
        self.setMinimumSize(960, 680)
        self.resize(1120, 780)
        root = QVBoxLayout(self)
        root.setContentsMargins(24, 22, 24, 18)
        root.setSpacing(18)
        header = QHBoxLayout()
        title = QVBoxLayout()
        title.setSpacing(6)
        title.addWidget(SubtitleLabel('AI 优化', self))
        title.addWidget(_muted(CaptionLabel('选择处理要求，对照确认讲稿修改。', self)))
        header.addLayout(title, 1)
        self.stage_tabs = WorkspaceSwitch(272, self)
        self.setup_step = self.stage_tabs.addItem('setup', '1  设置任务', onClick=self.show_setup)
        self.review_step = self.stage_tabs.addItem('review', '2  审查结果', onClick=self.show_review)
        self.stage_tabs.setCurrentItem('setup')
        header.addWidget(self.stage_tabs)
        root.addLayout(header)
        self.progress = ProgressBar(self)
        self.progress.setFixedHeight(3)
        self.progress.hide()
        root.addWidget(self.progress)
        self.stage_stack = QStackedWidget(self)
        self.stage_stack.addWidget(self._build_setup())
        self.stage_stack.addWidget(self._build_review())
        root.addWidget(self.stage_stack, 1)

        footer = QHBoxLayout()
        footer.setSpacing(12)
        footer.addStretch()
        self.cancel_task_button = PushButton('停止处理', self)
        self.cancel_task_button.clicked.connect(self.cancel_rewrite)
        footer.addWidget(self.cancel_task_button)
        self.import_result_button = PushButton('导入优化结果', self)
        self.import_result_button.clicked.connect(self.import_result)
        footer.addWidget(self.import_result_button)
        self.start_button = PrimaryPushButton('开始优化', self)
        self.start_button.clicked.connect(self.start_rewrite)
        footer.addWidget(self.start_button)
        self.export_task_button = PrimaryPushButton('导出优化任务', self)
        self.export_task_button.clicked.connect(self.export_task)
        footer.addWidget(self.export_task_button)
        self.apply_button = PrimaryPushButton('应用所选修改', self)
        self.apply_button.clicked.connect(self.apply_selected)
        footer.addWidget(self.apply_button)
        for button in (self.cancel_task_button, self.start_button,
                       self.export_task_button, self.import_result_button, self.apply_button):
            button.setFixedHeight(36)
            button.setMinimumWidth(128)
        root.addLayout(footer)

    def _workspace(self):
        surface = _frame(self, 'rewriteSurface',
                         'QFrame#rewriteSurface { background: #FFFFFF; border: 1px solid #E4E4E7; border-radius: 12px; }',
                         'QFrame#rewriteSurface { background: #292929; border: 1px solid #414141; border-radius: 12px; }')
        layout = QHBoxLayout(surface)
        layout.setContentsMargins(1, 1, 1, 1)
        layout.setSpacing(0)
        sidebar = _frame(surface, 'rewriteSidebar',
                         'QFrame#rewriteSidebar { background: #F8F8FA; border-top-left-radius: 11px; border-bottom-left-radius: 11px; }',
                         'QFrame#rewriteSidebar { background: #252525; border-top-left-radius: 11px; border-bottom-left-radius: 11px; }')
        sidebar.setFixedWidth(252)
        left = QVBoxLayout(sidebar)
        left.setContentsMargins(12, 22, 12, 12)
        left.setSpacing(10)
        layout.addWidget(sidebar)
        line = QFrame(surface)
        line.setFixedWidth(1)
        line.setStyleSheet('background: rgba(128,128,128,0.16); border: none;')
        layout.addWidget(line)
        return surface, layout, sidebar, left

    def _page_picker(self, parent, layout, *, review=False):
        heading = QVBoxLayout()
        heading.setContentsMargins(12, 0, 12, 0)
        heading.setSpacing(7)
        heading.addWidget(StrongBodyLabel('应用页面' if review else '处理页面', parent))
        layout.addLayout(heading)
        controls = QHBoxLayout()
        controls.setContentsMargins(15, 4, 10, 4)
        controls.setSpacing(8)
        checkbox = CheckBox('全选修改' if review else '全选', parent)
        checkbox.setTristate(True)
        handler = self.set_all_results_checked if review else self.set_all_checked
        checkbox.clicked.connect(lambda: handler(checkbox.checkState() != Qt.CheckState.Unchecked))
        controls.addWidget(checkbox)
        controls.addStretch()
        summary = _muted(CaptionLabel(parent))
        font = summary.font()
        font.setPixelSize(12)
        summary.setFont(font)
        summary.setAlignment(Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter)
        controls.addWidget(summary)
        layout.addLayout(controls)
        listing = ListWidget(parent)
        listing.setItemDelegate(ManuscriptPageDelegate(listing))
        listing.setAccessibleName('应用页面' if review else '处理页面')
        style = 'ListWidget { border: none; background: transparent; outline: none; padding: 0; }'
        setCustomStyleSheet(listing, style, style)
        layout.addWidget(listing, 1)
        if review:
            self.select_results_checkbox, self.result_selection_summary = checkbox, summary
        else:
            self.select_pages_checkbox, self.page_selection_summary = checkbox, summary
        return listing

    def _build_setup(self):
        surface, layout, sidebar, left = self._workspace()
        self.page_list = self._page_picker(sidebar, left)
        self.setup_scroll = ScrollArea(surface)
        self.setup_scroll.setWidgetResizable(True)
        self.setup_scroll.enableTransparentBackground()
        self.setup_scroll.viewport().setAutoFillBackground(False)
        content = QWidget()
        content.setObjectName('rewriteSettings')
        content.setStyleSheet('QWidget#rewriteSettings { background: transparent; }')
        settings = QVBoxLayout(content)
        settings.setContentsMargins(24, 22, 24, 20)
        settings.setSpacing(14)
        row = QHBoxLayout()
        row.setSpacing(14)
        field_label = StrongBodyLabel('优化场景', content)
        field_label.setFixedWidth(72)
        row.addWidget(field_label)
        self.style_combo = ComboBox(content)
        self.style_combo.setFixedWidth(180)
        self.style_combo.setFixedHeight(36)
        self.style_combo.setAccessibleName('优化场景')
        row.addWidget(self.style_combo)
        row.addStretch()
        self.style_button = PushButton('管理场景', content)
        self.style_button.setFixedSize(88, 36)
        self.style_button.clicked.connect(self.open_style_manager)
        row.addWidget(self.style_button)
        settings.addLayout(row)
        self.scene_hint = _muted(BodyLabel(content))
        self.scene_hint.setWordWrap(True)
        description = QHBoxLayout()
        description.setSpacing(0)
        description.addSpacing(86)
        description.addWidget(self.scene_hint, 1)
        settings.addLayout(description)
        settings.addWidget(HorizontalSeparator(content))
        row = QHBoxLayout()
        row.setSpacing(14)
        field_label = StrongBodyLabel('处理方式', content)
        field_label.setFixedWidth(72)
        row.addWidget(field_label)
        self.mode_tabs = WorkspaceSwitch(224, content)
        self.mode_tabs.addItem('api', '接口处理', onClick=lambda: self.set_processing_mode('api'))
        self.mode_tabs.addItem('external', '外部处理', onClick=lambda: self.set_processing_mode('external'))
        self.mode_tabs.setCurrentItem('api')
        row.addWidget(self.mode_tabs)
        row.addStretch()
        self.config_button = PushButton('接口配置', content)
        self.config_button.setFixedSize(88, 36)
        self.config_button.clicked.connect(self.open_config_dialog)
        row.addWidget(self.config_button)
        settings.addLayout(row)
        self.mode_stack = QStackedWidget(content)
        api = QWidget(content)
        api_row = QHBoxLayout(api)
        api_row.setContentsMargins(86, 0, 0, 0)
        self.connection_hint = _muted(BodyLabel(api))
        self.connection_hint.setWordWrap(True)
        api_row.addWidget(self.connection_hint, 1)
        self.mode_stack.addWidget(api)
        external = QWidget(content)
        external_row = QHBoxLayout(external)
        external_row.setContentsMargins(86, 0, 0, 0)
        external_hint = _muted(BodyLabel('导出任务，在其他 AI 中处理后导入结果，再逐页审查。', external))
        external_hint.setWordWrap(True)
        external_row.addWidget(external_hint)
        self.mode_stack.addWidget(external)
        settings.addWidget(self.mode_stack)
        settings.addWidget(HorizontalSeparator(content))
        heading = QHBoxLayout()
        self.source_label = StrongBodyLabel('讲稿预览', content)
        heading.addWidget(self.source_label)
        heading.addStretch()
        self.source_meta = _muted(CaptionLabel(content))
        heading.addWidget(self.source_meta)
        settings.addLayout(heading)
        self.source_preview = _editor(content, reading=True)
        self.source_preview.setReadOnly(True)
        self.source_preview.setMinimumHeight(170)
        settings.addWidget(self.source_preview, 1)
        self.setup_scroll.setWidget(content)
        layout.addWidget(self.setup_scroll, 1)
        return surface

    def _build_review(self):
        surface, layout, sidebar, left = self._workspace()
        self.review_list = self._page_picker(sidebar, left, review=True)
        content = QWidget(surface)
        body = QVBoxLayout(content)
        body.setContentsMargins(22, 22, 22, 20)
        body.setSpacing(16)
        header = QHBoxLayout()
        self.review_title = StrongBodyLabel('逐页审查', content)
        font = self.review_title.font()
        font.setPixelSize(18)
        self.review_title.setFont(font)
        header.addWidget(self.review_title, 1)
        self.review_summary = _muted(CaptionLabel(content))
        header.addWidget(self.review_summary)
        body.addLayout(header)
        self.warning_panel = _frame(content, 'rewriteWarning',
                                    'QFrame#rewriteWarning { background: #FFF6E5; border: none; border-radius: 6px; }',
                                    'QFrame#rewriteWarning { background: #403725; border: none; border-radius: 6px; }')
        warning_layout = QVBoxLayout(self.warning_panel)
        warning_layout.setContentsMargins(10, 10, 10, 10)
        self.warning_label = CaptionLabel(self.warning_panel)
        self.warning_label.setWordWrap(True)
        self.warning_label.setTextColor(QColor('#805500'), QColor('#E7BC70'))
        warning_layout.addWidget(self.warning_label)
        self.warning_label.hide()
        self.warning_panel.hide()
        body.addWidget(self.warning_panel)
        self.comparison = QSplitter(Qt.Orientation.Horizontal, content)
        self.comparison.setHandleWidth(14)
        self.comparison.setChildrenCollapsible(False)
        self.original_label = _muted(CaptionLabel('原文', content))
        self.rewritten_label = StrongBodyLabel('优化结果', content)
        self.original_edit = _editor(content, reading=True)
        self.original_edit.setReadOnly(True)
        self.rewritten_edit = _editor(content)
        self.rewritten_edit.setReadOnly(True)
        self.rewritten_edit.setPlaceholderText('优化结果将在这里显示')
        self.comparison.addWidget(_pane(self.original_label, self.original_edit, content))
        self.comparison.addWidget(_pane(self.rewritten_label, self.rewritten_edit, content))
        self.comparison.setSizes([400, 400])
        body.addWidget(self.comparison, 1)
        layout.addWidget(content, 1)
        return surface
